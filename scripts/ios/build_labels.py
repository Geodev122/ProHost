#!/usr/bin/env python3
"""Android `AR_LABELS` (ui/util/LocalizedLabels.kt) -> `ios/ProHost/Core/Util/LocalizedLabels.swift`. `--check` fails when stale."""
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
SRC = ROOT / "app/src/main/java/com/example/ui/util/LocalizedLabels.kt"
OUT = ROOT / "ios/ProHost/Core/Util/LocalizedLabels.swift"


def build():
    text = SRC.read_text(encoding="utf-8")
    body = text[text.index("mapOf("):text.index("\n)\n", text.index("mapOf("))]
    pairs = re.findall(r'"((?:[^"\\]|\\.)*)"\s+to\s+"((?:[^"\\]|\\.)*)"', body)
    lines = ["// GENERATED by scripts/ios/build_labels.py from LocalizedLabels.kt (AR_LABELS). Do not edit.",
             "import Foundation", "",
             "/// Arabic for the fixed English labels that live in the data layer; stored values stay English, translate only where shown.",
             "enum LocalizedLabels {", "    static let arabic: [String: String] = ["]
    for en, ar in pairs:
        lines.append(f'        "{en}": "{ar}",')
    lines += ["    ]", "}", "",
              "/// The label in the app language (Arabic when the app runs in Arabic), else unchanged.",
              "func localizedLabel(_ english: String) -> String {",
              '    Locale.current.language.languageCode?.identifier == "ar" ? (LocalizedLabels.arabic[english] ?? english) : english',
              "}", ""]
    return "\n".join(lines), len(pairs)


if __name__ == "__main__":
    content, n = build()
    if "--check" in sys.argv:
        if not OUT.exists() or OUT.read_text(encoding="utf-8") != content:
            print("LocalizedLabels.swift is stale: run python3 scripts/ios/build_labels.py")
            sys.exit(1)
        print(f"labels in sync ({n})")
    else:
        OUT.parent.mkdir(parents=True, exist_ok=True)
        OUT.write_text(content, encoding="utf-8")
        print(f"{n} labels -> {OUT.relative_to(ROOT)}")
