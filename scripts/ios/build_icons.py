#!/usr/bin/env python3
"""Android Material icons -> iOS asset catalog + Swift enum (Apache-2.0 icons from @material-design-icons/svg).

Scans the Kotlin sources for `Icons.(AutoMirrored.)?(Default|Filled|Outlined|Rounded).Name`, copies the matching SVG into
`ios/ProHost/Resources/Assets.xcassets/Icons/<asset>.imageset` (template rendering, vector preserved) and writes
`ios/ProHost/DesignSystem/PHIcon.swift`. Re-run after Android starts using a new icon; CI runs `--check`.

  build_icons.py            generate (needs npm for the first run; the package is cached in $ICON_CACHE or /tmp)
  build_icons.py --check    fail if an icon used by Android is missing from the generated Swift enum
"""
import glob
import json
import os
import re
import shutil
import subprocess
import sys
import tarfile
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
KT = ROOT / "app/src/main/java"
ASSETS = ROOT / "ios/ProHost/Resources/Assets.xcassets/Icons"
SWIFT = ROOT / "ios/ProHost/DesignSystem/PHIcon.swift"
PKG = "@material-design-icons/svg@0.14.15"
STYLE_DIR = {"Default": "filled", "Filled": "filled", "Outlined": "outlined", "Rounded": "round"}
STYLE_TAG = {"Default": "filled", "Filled": "filled", "Outlined": "outlined", "Rounded": "rounded"}
SPECIAL = {"AddAPhoto": "add_a_photo"}
PAT = re.compile(r"Icons\.(AutoMirrored\.)?(Default|Filled|Outlined|Rounded)\.([A-Za-z0-9]+)")


def snake(name):
    return SPECIAL.get(name) or re.sub(r"(?<=[a-z0-9])(?=[A-Z])", "_", name).lower()


def used_icons():
    found = {}
    for f in glob.glob(str(KT / "**/*.kt"), recursive=True):
        for m in PAT.finditer(Path(f).read_text(encoding="utf-8")):
            key = (STYLE_TAG[m.group(2)], m.group(3))
            found[key] = found.get(key, False) or bool(m.group(1))
    return found


def lower_first(s):
    return s[0].lower() + s[1:]


def case_name(style, name):
    return lower_first(style) + name  # filledSearch, outlinedReceiptLong


def package_dir():
    cache = Path(os.environ.get("ICON_CACHE", "/tmp/material-icons-cache"))
    pkg = cache / "package"
    if not pkg.exists():
        cache.mkdir(parents=True, exist_ok=True)
        out = subprocess.check_output(["npm", "pack", PKG, "--silent"], cwd=cache, text=True).strip().splitlines()[-1]
        with tarfile.open(cache / out) as t:
            t.extractall(cache)
    return pkg


def generate():
    icons = used_icons()
    pkg = package_dir()
    if ASSETS.exists():
        shutil.rmtree(ASSETS)
    ASSETS.mkdir(parents=True)
    cases = []
    for (style, name), mirrored in sorted(icons.items()):
        folder = {"filled": "filled", "outlined": "outlined", "rounded": "round"}[style]
        src = pkg / folder / f"{snake(name)}.svg"
        if not src.exists():
            sys.exit(f"missing icon file for {style}.{name}: {src}")
        asset = f"ic_{style}_{snake(name)}"
        d = ASSETS / f"{asset}.imageset"
        d.mkdir()
        shutil.copy(src, d / f"{asset}.svg")
        (d / "Contents.json").write_text(json.dumps({
            "images": [{"filename": f"{asset}.svg", "idiom": "universal"}],
            "info": {"author": "xcode", "version": 1},
            "properties": {"preserves-vector-representation": True, "template-rendering-intent": "template"},
        }, indent=2) + "\n")
        cases.append((case_name(style, name), asset, mirrored))
    (ASSETS / "Contents.json").write_text(json.dumps({"info": {"author": "xcode", "version": 1}}, indent=2) + "\n")
    lines = ["// GENERATED by scripts/ios/build_icons.py from the icons the Android app uses (Material Icons, Apache-2.0). Do not edit.",
             "import SwiftUI", "", "enum PHIcon: String, CaseIterable {"]
    for case, asset, _ in cases:
        lines.append(f'    case {case} = "{asset}"')
    lines += ["", "    /// Icons Android draws with `Icons.AutoMirrored`: they flip in right-to-left layouts.",
              "    var autoMirrored: Bool {", "        switch self {"]
    mirrored = [c for c, _, m in cases if m]
    if mirrored:
        lines.append("        case " + ", ".join("." + c for c in mirrored) + ":")
        lines.append("            return true")
    lines += ["        default:", "            return false", "        }", "    }", "}", ""]
    SWIFT.write_text("\n".join(lines), encoding="utf-8")
    print(f"{len(cases)} icons -> {ASSETS.relative_to(ROOT)} and {SWIFT.relative_to(ROOT)}")


def check():
    text = SWIFT.read_text(encoding="utf-8") if SWIFT.exists() else ""
    missing = [f"{s}.{n}" for (s, n) in used_icons() if f"case {case_name(s, n)} " not in text]
    if missing:
        print("PHIcon.swift is stale, missing:", ", ".join(missing))
        print("Run: python3 scripts/ios/build_icons.py and commit the result")
        sys.exit(1)
    print("icons in sync with Android")


if __name__ == "__main__":
    check() if "--check" in sys.argv else generate()
