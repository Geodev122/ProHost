#!/usr/bin/env python3
"""Generate / refresh the per-file unit table in docs/migration/PARITY.md.

    python3 scripts/migration/gen_parity_table.py [--write] [--check]

Scans app/src/main/java/com/example, classifies every Kotlin file and keeps the status columns of rows that already
exist. Classes (docs/migration/MASTER_PLAN.md section 2):
  X  admin (moves to adminWeb, never to shared/iOS)         C  Android-only, stays behind an interface
  B  shareable Compose/Kotlin that needs an Android seam    A2 pure but uses JVM java.* / Calendar / String.format
  A1 compiles in commonMain after the R -> Res / Coil swap
The class here is an automatic first guess from imports and an explicit C/X list; the 'learn' step of each unit
confirms or corrects it (edit the Class cell by hand; it is preserved).
"""
from __future__ import annotations

import argparse
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
SRC = ROOT / "app/src/main/java/com/example"
DOC = ROOT / "docs/migration/PARITY.md"
BEGIN, END = "<!-- PARITY-TABLE:BEGIN (generated by scripts/migration/gen_parity_table.py; status cells are kept) -->", "<!-- PARITY-TABLE:END -->"
HEADER = "| Unit (file) | Lines | Class | Seams / reasons | Goldens | Tests | Android diff = 0 | iOS sheet | Status |\n|---|---|---|---|---|---|---|---|---|"

ADMIN = {
    "ui/screens/AdminConsoleScreen.kt", "ui/screens/AdminAnalyticsScreen.kt", "ui/viewmodel/AdminViewModel.kt",
    "ui/state/AdminUiState.kt", "ui/components/AdminGrantAccessCard.kt", "ui/components/dialogs/SystemDebuggerDialog.kt",
    "util/AppSystemDebugger.kt", "data/auth/AdminDirectoryModels.kt", "data/demo/DemoDataGenerator.kt",
}
ANDROID_ONLY = {
    "MainActivity.kt", "ProHostApplication.kt", "service/ProHostMessagingService.kt", "data/auth/FirebaseAuthService.kt",
    "data/auth/FirebaseFunctionsClient.kt", "data/auth/GoogleCredentialState.kt", "data/billing/PlayBillingManager.kt",
    "data/billing/PlayBillingSecurity.kt", "data/firestore/FirestoreService.kt", "data/storage/FirebaseStorageService.kt",
    "legal/LegalPdfGenerator.kt", "util/InAppUpdateManager.kt", "util/NotificationPermissionManager.kt",
    "util/PhoneCountryDetector.kt", "util/PlayIntegrityManager.kt", "ui/util/ContextUtils.kt", "analytics/AnalyticsSink.kt",
    "ui/components/PhoneNumberHint.kt", "ui/theme/FontScaleCap.kt", "ui/viewmodel/BillingController.kt",
}
SEAMS = [  # (regex on file text, seam name)
    (r"^import android\.content\.Intent|Intent\.ACTION", "PlatformActions"),
    (r"^import android\.net\.Uri", "MediaPicker(PickedFile)"),
    (r"ActivityResultContracts|rememberLauncherForActivityResult", "MediaPicker/Permissions"),
    (r"^import android\.util\.Log", "Logger"),
    (r"ClipboardManager|ClipData", "Clipboard"),
    (r"^import android\.widget\.Toast", "Messenger"),
    (r"MediaPlayer|AudioAttributes", "SoundPlayer"),
    (r"Geocoder|FusedLocation|android\.location", "Location/Geocoder"),
    (r"com\.google\.maps\.android|com\.google\.android\.gms\.maps|GoogleMap", "MapView"),
    (r"^import coil\.", "Coil3"),
    (r"android\.webkit\.WebView", "HtmlView"),
    (r"android\.graphics\.(Bitmap|Canvas|Paint|pdf)", "ImageCodec/Pdf"),
    (r"androidx\.activity\.compose\.BackHandler", "BackHandler"),
    (r"HapticFeedback|performHapticFeedback", "Haptics"),
    (r"SharedPreferences", "KeyValueStore"),
    (r"com\.google\.firebase", "Firebase gateways"),
    (r"com\.android\.billingclient", "SubscriptionStore"),
    (r"androidx\.credentials", "GoogleSignIn"),
    (r"LocalContext\.current|\bcontext: Context|\bContext\b", "Context removal"),
    (r"AutofillNode|LocalAutofill", "Autofill"),
    (r"android\.provider\.CalendarContract", "PlatformActions(calendar)"),
]
JVM = re.compile(r"java\.(util\.(Calendar|Locale|UUID|Date|TimeZone|Currency)|text\.|security\.)|String\.format|\.format\(|System\.currentTimeMillis|LocalConfiguration")
ANDROID_IMPORT = re.compile(r"^import android\.(?!annotation)", re.M)


def classify(rel: str, text: str) -> tuple[str, list[str]]:
    seams = sorted({name for rx, name in SEAMS if re.search(rx, text, re.M)})
    if rel in ADMIN or rel.startswith("ui/screens/admin/"):
        return "X", ["admin → adminWeb"]
    if rel in ANDROID_ONLY:
        return "C", seams or ["Android-only"]
    android_use = bool(ANDROID_IMPORT.search(text)) or any(
        s in seams for s in ("MapView", "Location/Geocoder", "HtmlView", "MediaPicker/Permissions", "Autofill", "SubscriptionStore", "GoogleSignIn", "BackHandler"))
    if android_use:
        return "B", seams
    if JVM.search(text):
        return "A2", seams + ["java.* → kotlinx-datetime/expect"]
    return "A1", seams


def scan() -> list[tuple[str, int, str, list[str]]]:
    rows = []
    for p in sorted(SRC.rglob("*.kt")):
        rel = p.relative_to(SRC).as_posix()
        text = p.read_text(encoding="utf-8")
        cls, seams = classify(rel, text)
        rows.append((rel, text.count("\n") + 1, cls, seams))
    return rows


def existing_cells() -> dict[str, list[str]]:
    if not DOC.exists() or BEGIN not in DOC.read_text():
        return {}
    block = DOC.read_text().split(BEGIN)[1].split(END)[0]
    cells = {}
    for line in block.splitlines():
        m = re.match(r"\|\s*`([^`]+)`\s*\|(.*)\|\s*$", line)
        if m:
            cells[m.group(1)] = [c.strip() for c in m.group(2).split("|")]
    return cells


def render(rows) -> str:
    old = existing_cells()
    out = [BEGIN, HEADER]
    for rel, lines, cls, seams in rows:
        prev = old.get(rel)
        # keep hand-edited class and the status columns
        cls_cell = prev[1] if prev else cls
        tail = prev[3:] if prev and len(prev) >= 8 else ["", "", "☐", "☐", "todo" if cls != "X" else "adminWeb"]
        out.append(f"| `{rel}` | {lines} | {cls_cell} | {', '.join(seams) or '—'} | " + " | ".join(tail) + " |")
    totals = {}
    for _, lines, cls, _ in rows:
        totals.setdefault(cls, [0, 0])
        totals[cls][0] += 1
        totals[cls][1] += lines
    out.append(END)
    out.append("")
    out.append("Automatic class totals (files / lines): " + ", ".join(f"{k} {v[0]} / {v[1]}" for k, v in sorted(totals.items())) + ".")
    return "\n".join(out)


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--write", action="store_true", help="rewrite the generated block in PARITY.md")
    ap.add_argument("--check", action="store_true", help="fail if PARITY.md is missing a source file or lists a removed one")
    a = ap.parse_args()
    rows = scan()
    if a.check:
        listed = set(existing_cells())
        actual = {r[0] for r in rows}
        missing, stale = sorted(actual - listed), sorted(listed - actual)
        for m in missing:
            print(f"MISSING in PARITY.md: {m}")
        for s in stale:
            print(f"STALE in PARITY.md (file gone; mark it 'removed' by deleting the row once the unit is done): {s}")
        return 1 if missing or stale else 0
    text = render(rows)
    if a.write:
        doc = DOC.read_text()
        head = doc.split(BEGIN)[0] if BEGIN in doc else doc.rstrip() + "\n\n"
        tail = doc.split(END, 1)[1].split("\n", 2)[2] if END in doc and "\n" in doc.split(END, 1)[1] else ""
        DOC.write_text(head + text + "\n" + tail.lstrip("\n"))
        print(f"wrote {len(rows)} rows to {DOC.relative_to(ROOT)}")
    else:
        print(text)
    return 0


if __name__ == "__main__":
    sys.exit(main())
